export type PromiseStatus =
  | "NOT_STARTED"
  | "IN_PROGRESS"
  | "REPORTED_COMPLETED"
  | "VERIFIED_COMPLETED"
  | "UNABLE_TO_VERIFY"
  | "EVIDENCE_CONFLICTING";

export type ElectionResult = "won" | "lost";

/** A dated, attributable source behind a promise status. */
export interface EvidenceSource {
  title: string;
  publisher: string;
  url: string;
  /** Publication date, YYYY-MM-DD */
  date: string;
  /** Verbatim line from the source, kept short */
  quote?: string;
}

export interface PilotPromise {
  id: string;
  title: string;
  sourceNote?: string;
  announcedDate?: string;
  status: PromiseStatus;
  evidenceNote?: string;
  lastChecked?: string;
  /** Evidence behind the current status. Required for any status other than UNABLE_TO_VERIFY. */
  sources?: EvidenceSource[];
  likes: number;
  dislikes: number;
}

